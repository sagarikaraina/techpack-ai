/**
 * NUON Basic Blocks — Fit & Sizing Repository
 * Source: NUON BASIC BLOCKS.pdf
 *
 * Each entry represents a standard garment style with its fit category
 * and base-size measurements (all values in cm).
 */

export interface FitMeasurement {
  id: string;
  name: string;
  value: number;
  unit: string;
}

export interface FitBlock {
  body: string;           // e.g. "SLIM CROP TEE"
  fit: string;            // e.g. "SLIM", "BOXY", "OVERSIZED", "SKINNY"
  reference: string;      // internal reference name
  keywords: string[];     // search keywords for matching
  measurements: FitMeasurement[];
}

function m(id: string, name: string, value: number): FitMeasurement {
  return { id, name, value, unit: 'cm' };
}

